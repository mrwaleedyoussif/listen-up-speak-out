"""MAP Growth department: turns the content files in tools/map (map_reading_g3.json … g9.json, and later
map_language_g3.json … g9.json) into small scripts in www/map that the app loads one grade at a time.
Run after changing anything in tools/map:   python3 tools/app/build_map_data.py"""
import collections, glob, json, os, re
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
SRC, OUT = os.path.join(ROOT, 'tools', 'map'), os.path.join(ROOT, 'www', 'map')
os.makedirs(OUT, exist_ok=True)
TYPES = {'multiple-choice': 'mc', 'multiple-select (choose two)': 'ms', 'two-part': 'tp'}
GOAL = {'Literary Text': 'LT', 'Informational Text': 'IT', 'Vocabulary': 'VO',
        'Writing': 'WR', 'Grammar and Usage': 'GU', 'Mechanics': 'ME'}  # Language Usage files already use WR/GU/ME

def item(q):
    it = {'n': q['n'], 't': TYPES[q['type']], 's': q['stem'], 'o': q['options'], 'k': q['key'], 'sk': q['skill'], 'b': q['rit_band']}
    if q.get('goal'): it['g'] = GOAL.get(q['goal'], q['goal'])
    if q.get('part_b'): it['pb'] = {'s': q['part_b']['stem'], 'o': q['part_b']['options'], 'k': q['part_b']['key']}
    return it

def passage(p):
    if not p: return None
    out = {'title': p['title'], 'genre': p.get('genre', ''), 'paras': p['paras']}
    if p.get('poem'): out['poem'] = True
    if p.get('intro'): out['intro'] = p['intro']
    return out

def rit_units(units, P):
    """Regroup the practice questions by RIT band: RIT 1 = 151–160, RIT 2 = 161–170, … (10 points each).
    Inside a RIT unit, every practice is one text (or one group of sentences) with its questions from that band.
    Texts are stored once in P and referred to by number."""
    seen, chunks = {}, {}
    for u in units:
        for st in u['sets']:
            pi = None
            if st['passage']:
                key = json.dumps(st['passage'], sort_keys=True, ensure_ascii=False)
                if key not in seen: seen[key] = len(P); P.append(st['passage'])
                pi = seen[key]
            by = collections.OrderedDict()
            for it in st['items']: by.setdefault(it['b'], []).append(it)
            for b, its in by.items():
                goal = collections.Counter(i.get('g') or u['goal'] for i in its).most_common(1)[0][0]
                chunks.setdefault(b, []).append({'p': pi, 'goal': goal, 'items': [dict(it, n=j) for j, it in enumerate(its, 1)]})
    out = []
    for b in sorted(chunks, key=lambda x: int(x[:3])):
        lo = int(b[:3]); n = (lo - 151) // 10 + 1
        assert n >= 1 and (lo - 151) % 10 == 0, b
        sets = chunks[b]
        for i, st in enumerate(sets, 1): st['set'] = str(i)
        sk = [k for k, _ in collections.Counter(it['sk'] for st in sets for it in st['items']).most_common(4)]
        out.append({'id': f'R{n}', 'n': n, 'title': f'RIT {n}', 'goal': 'RIT', 'band': b, 'skills': sk, 'vocab': [], 'sets': sets})
    return out

made, index, counts = [], {'reading': [], 'language': []}, {}
for f in sorted(glob.glob(os.path.join(SRC, 'map_*_g*.json'))):
    subj, g = re.match(r'map_(\w+)_g(\d+)\.json', os.path.basename(f)).groups()
    d = json.load(open(f, encoding='utf-8'))
    out = {'grade': int(g), 'subject': subj,
           'units': [{'id': u['id'], 'title': u['title'], 'goal': GOAL.get(u['goal'], u['goal']), 'band': u['rit_band'], 'skills': u['skills'],
                      'vocab': u.get('vocab', []),
                      'sets': [{'set': p['set'], 'passage': passage(p['passage']), 'items': [item(q) for q in p['items']]} for p in u['practice']]}
                     for u in d['units']],
           'mocks': [{'id': M['id'], 'note': M['note'],
                      'sections': [dict({'passage': passage(s['passage']), 'items': [item(q) for q in s['items']]}, **({'label': s['label']} if s.get('label') else {}))
                                   for s in M['sections']]}
                     for M in d['mocks']]}
    out['pass'] = []
    out['units'] = rit_units(out['units'], out['pass'])
    counts[f'{subj}_{g}'] = {'u': len(out['units']), 's': sum(len(u['sets']) for u in out['units']), 'q': sum(len(s['items']) for u in out['units'] for s in u['sets'])}
    n_items = sum(len(s['items']) for u in out['units'] for s in u['sets']) + sum(len(s['items']) for M in out['mocks'] for s in M['sections'])
    js = f'/* MAP Growth {subj} practice, Grade {g} (generated by tools/app/build_map_data.py; original material by Waleed Youssef) */\n' \
         f'(window.MAP_DATA = window.MAP_DATA || {{}})["{subj}_{g}"] = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n' \
         f'(function(d){{d.units.forEach(function(u){{u.sets.forEach(function(s){{s.passage=s.p==null?null:d.pass[s.p];}});}});}})(window.MAP_DATA["{subj}_{g}"]);\n'
    open(os.path.join(OUT, f'{subj}_g{g}.js'), 'w', encoding='utf-8').write(js)
    made.append(f'{subj} G{g}: {n_items} questions'); index.setdefault(subj, []).append(int(g))
for k in index: index[k] = sorted(index[k])
# print copies in print/map/ (repo root): MAP_<Subject>_G<g>_Student_Booklet / _Mock_Exams, .pdf and .docx
PRINT = os.path.join(ROOT, 'print', 'map')
prn = {}
for f in sorted(os.listdir(PRINT)) if os.path.isdir(PRINT) else []:
    m = re.fullmatch(r'MAP_(Reading|Language)_G(\d)_(Student_Booklet|Mock_Exams)\.(pdf|docx)', f)
    if m:
        key = ('reading' if m.group(1) == 'Reading' else 'language') + '_' + m.group(2)
        kind = 'booklet' if m.group(3) == 'Student_Booklet' else 'mocks'
        prn.setdefault(key, {}).setdefault(kind, {})[m.group(4)] = {'f': f, 'b': os.path.getsize(os.path.join(PRINT, f))}
open(os.path.join(OUT, 'index.js'), 'w', encoding='utf-8').write('/* Which MAP subjects and grades have material, and their print copies (generated) */\nwindow.MAP_INDEX = ' + json.dumps(index) + ';\n'
    + '/* RIT units, practices and practice questions in each grade */\nwindow.MAP_COUNTS = ' + json.dumps(counts, separators=(',', ':')) + ';\n'
    + 'window.MAP_PRINT = ' + json.dumps(prn, separators=(',', ':')) + ';\n')
print('print copies:', sum(len(v) for k in prn.values() for v in k.values()))
print('\n'.join(made)); print('index:', index)
